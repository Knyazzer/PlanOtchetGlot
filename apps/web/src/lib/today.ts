// Локальная календарная дата «сегодня» в формате YYYY-MM-DD.
// НЕ использовать `new Date().toISOString().slice(0,10)` — тот отдаёт UTC-дату, и на положительном
// смещении (напр. UTC+3) в промежутке между локальной и UTC-полночью возвращает ВЧЕРАШНЮЮ дату.
// Из-за этого клиент считал «сегодня» на день позже сервера (тот берёт локаль): сегодняшний день
// выглядел «будущим» (нет кнопки «Начать»), а вчерашний — «сегодняшним». Считаем по локальным полям.
export function todayISO(): string {
  const n = new Date()
  const p = (x: number) => String(x).padStart(2, '0')
  return `${n.getFullYear()}-${p(n.getMonth() + 1)}-${p(n.getDate())}`
}
